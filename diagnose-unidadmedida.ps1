# Script de Diagnóstico - UnidadMedida
Write-Host "`n????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?                                                              ?" -ForegroundColor Cyan
Write-Host "?    ?? DIAGNÓSTICO - UNIDADES DE MEDIDA                      ?" -ForegroundColor Cyan
Write-Host "?                                                              ?" -ForegroundColor Cyan
Write-Host "????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$errores = 0

# ????????????????????????????????????????????????????????????????
# 1. Verificar procesos
# ????????????????????????????????????????????????????????????????
Write-Host "1??  Verificando procesos..." -ForegroundColor Yellow
Write-Host "   ?????????????????????????????????????" -ForegroundColor DarkGray

$apiProcess = Get-Process -Name "AgoraHub360.ERP.Api" -ErrorAction SilentlyContinue
$webProcess = Get-Process -Name "AgoraHub360.ERP.Web" -ErrorAction SilentlyContinue

if ($apiProcess) {
    Write-Host "   ? API corriendo " -NoNewline -ForegroundColor Green
    Write-Host "(PID: $($apiProcess.Id))" -ForegroundColor Gray
} else {
    Write-Host "   ? API NO está corriendo" -ForegroundColor Red
    Write-Host "      ?? Ejecuta: " -NoNewline -ForegroundColor Yellow
    Write-Host "cd src\AgoraHub360.ERP.Api; dotnet run" -ForegroundColor Cyan
    $errores++
}

if ($webProcess) {
    Write-Host "   ? Web corriendo " -NoNewline -ForegroundColor Green
    Write-Host "(PID: $($webProcess.Id))" -ForegroundColor Gray
} else {
    Write-Host "   ? Web NO está corriendo" -ForegroundColor Red
    Write-Host "      ?? Ejecuta: " -NoNewline -ForegroundColor Yellow
    Write-Host "cd src\AgoraHub360.ERP.Web; dotnet run" -ForegroundColor Cyan
    $errores++
}

# ????????????????????????????????????????????????????????????????
# 2. Verificar puertos
# ????????????????????????????????????????????????????????????????
Write-Host "`n2??  Verificando puertos..." -ForegroundColor Yellow
Write-Host "   ?????????????????????????????????????" -ForegroundColor DarkGray

try {
    $apiPort = Test-NetConnection -ComputerName localhost -Port 7001 -WarningAction SilentlyContinue
    if ($apiPort.TcpTestSucceeded) {
        Write-Host "   ? Puerto 7001 (API) abierto" -ForegroundColor Green
    } else {
        Write-Host "   ? Puerto 7001 (API) cerrado" -ForegroundColor Red
        $errores++
    }
} catch {
    Write-Host "   ??  No se pudo verificar puerto 7001" -ForegroundColor Yellow
}

try {
    $webPort = Test-NetConnection -ComputerName localhost -Port 5002 -WarningAction SilentlyContinue
    if ($webPort.TcpTestSucceeded) {
        Write-Host "   ? Puerto 5002 (Web) abierto" -ForegroundColor Green
    } else {
        Write-Host "   ? Puerto 5002 (Web) cerrado" -ForegroundColor Red
        $errores++
    }
} catch {
    Write-Host "   ??  No se pudo verificar puerto 5002" -ForegroundColor Yellow
}

# ????????????????????????????????????????????????????????????????
# 3. Test de conexión a la API
# ????????????????????????????????????????????????????????????????
Write-Host "`n3??  Probando conexión a la API..." -ForegroundColor Yellow
Write-Host "   ?????????????????????????????????????" -ForegroundColor DarkGray

try {
    $healthCheck = Invoke-WebRequest -Uri "https://localhost:7001/health" `
        -SkipCertificateCheck `
        -TimeoutSec 5 `
        -ErrorAction Stop
    
    if ($healthCheck.StatusCode -eq 200) {
        Write-Host "   ? API responde correctamente" -ForegroundColor Green
        Write-Host "      Status: " -NoNewline -ForegroundColor Gray
        Write-Host "$($healthCheck.StatusCode) OK" -ForegroundColor Cyan
    }
} catch {
    Write-Host "   ? No se puede conectar a la API" -ForegroundColor Red
    Write-Host "      Error: " -NoNewline -ForegroundColor Gray
    Write-Host "$($_.Exception.Message)" -ForegroundColor Red
    $errores++
}

# ????????????????????????????????????????????????????????????????
# 4. Verificar archivo de configuración Web
# ????????????????????????????????????????????????????????????????
Write-Host "`n4??  Verificando configuración Web..." -ForegroundColor Yellow
Write-Host "   ?????????????????????????????????????" -ForegroundColor DarkGray

$configPath = "src\AgoraHub360.ERP.Web\wwwroot\appsettings.json"
if (Test-Path $configPath) {
    Write-Host "   ? Archivo de configuración encontrado" -ForegroundColor Green
    try {
        $config = Get-Content $configPath | ConvertFrom-Json
        Write-Host "      ApiBaseUrl: " -NoNewline -ForegroundColor Gray
        Write-Host "$($config.ApiBaseUrl)" -ForegroundColor Cyan
        
        if ($config.ApiBaseUrl -eq "https://localhost:7001/" -or $config.ApiBaseUrl -eq "https://localhost:7001") {
            Write-Host "   ? URL base correcta" -ForegroundColor Green
        } else {
            Write-Host "   ??  URL base podría ser incorrecta" -ForegroundColor Yellow
        }
    } catch {
        Write-Host "   ? Error al leer configuración" -ForegroundColor Red
        $errores++
    }
} else {
    Write-Host "   ? Archivo de configuración NO encontrado" -ForegroundColor Red
    Write-Host "      Ruta esperada: $configPath" -ForegroundColor Gray
    $errores++
}

# ????????????????????????????????????????????????????????????????
# 5. Verificar compilación
# ????????????????????????????????????????????????????????????????
Write-Host "`n5??  Verificando compilación..." -ForegroundColor Yellow
Write-Host "   ?????????????????????????????????????" -ForegroundColor DarkGray

try {
    $buildResult = dotnet build --nologo --verbosity quiet 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Host "   ? Proyecto compila sin errores" -ForegroundColor Green
    } else {
        Write-Host "   ? Hay errores de compilación" -ForegroundColor Red
        $errores++
    }
} catch {
    Write-Host "   ??  No se pudo verificar compilación" -ForegroundColor Yellow
}

# ????????????????????????????????????????????????????????????????
# 6. Test del endpoint (si la API está corriendo)
# ????????????????????????????????????????????????????????????????
if ($apiProcess) {
    Write-Host "`n6??  Probando endpoint /api/v1/unidades-medida..." -ForegroundColor Yellow
    Write-Host "   ?????????????????????????????????????" -ForegroundColor DarkGray
    
    try {
        # Intento sin autenticación (debería dar 401)
        $response = Invoke-WebRequest -Uri "https://localhost:7001/api/v1/unidades-medida" `
            -SkipCertificateCheck `
            -TimeoutSec 5 `
            -ErrorAction Stop
        
        if ($response.StatusCode -eq 200) {
            Write-Host "   ? Endpoint responde (sin autenticación)" -ForegroundColor Green
        }
    } catch {
        $statusCode = $_.Exception.Response.StatusCode.value__
        if ($statusCode -eq 401) {
            Write-Host "   ? Endpoint existe (requiere autenticación)" -ForegroundColor Green
            Write-Host "      Status: " -NoNewline -ForegroundColor Gray
            Write-Host "401 Unauthorized (correcto)" -ForegroundColor Cyan
        } elseif ($statusCode -eq 404) {
            Write-Host "   ? Endpoint NO encontrado (404)" -ForegroundColor Red
            $errores++
        } else {
            Write-Host "   ??  Error inesperado: $statusCode" -ForegroundColor Yellow
        }
    }
} else {
    Write-Host "`n6??  Test de endpoint omitido (API no está corriendo)" -ForegroundColor Gray
}

# ????????????????????????????????????????????????????????????????
# RESUMEN
# ????????????????????????????????????????????????????????????????
Write-Host "`n??????????????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "?? RESUMEN DEL DIAGNÓSTICO" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor DarkGray

if ($errores -eq 0) {
    Write-Host "`n   ? " -NoNewline -ForegroundColor Green
    Write-Host "Sistema configurado correctamente" -ForegroundColor Green
    Write-Host "`n   El error 'Error al cargar unidades de medida' puede ser por:" -ForegroundColor White
    Write-Host "   1. Token JWT expirado - " -NoNewline -ForegroundColor Gray
    Write-Host "Volver a hacer login" -ForegroundColor Yellow
    Write-Host "   2. No hay empresa asignada - " -NoNewline -ForegroundColor Gray
    Write-Host "Verificar en Config ? Empresas" -ForegroundColor Yellow
    Write-Host "   3. Base de datos sin datos - " -NoNewline -ForegroundColor Gray
    Write-Host "Crear unidades de prueba" -ForegroundColor Yellow
} else {
    Write-Host "`n   ? " -NoNewline -ForegroundColor Red
    Write-Host "Se encontraron $errores problema(s)" -ForegroundColor Red
    Write-Host "`n   Revisa los items marcados con ? arriba" -ForegroundColor Yellow
}

Write-Host "`n??????????????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "?? PRÓXIMOS PASOS" -ForegroundColor Yellow
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor DarkGray

if ($errores -gt 0) {
    Write-Host "`n   1. Corregir los errores marcados arriba" -ForegroundColor White
    Write-Host "   2. Ejecutar: " -NoNewline -ForegroundColor White
    Write-Host ".\start-system.ps1" -ForegroundColor Cyan
    Write-Host "   3. Volver a probar en el navegador" -ForegroundColor White
} else {
    Write-Host "`n   1. Ir a: " -NoNewline -ForegroundColor White
    Write-Host "https://localhost:5002/login" -ForegroundColor Cyan
    Write-Host "   2. Login: " -NoNewline -ForegroundColor White
    Write-Host "admin@agorahub360.com / Admin123" -ForegroundColor Cyan
    Write-Host "   3. Ir a: " -NoNewline -ForegroundColor White
    Write-Host "Datos Maestros ? Unid. Medida" -ForegroundColor Cyan
    Write-Host "   4. Abrir DevTools (F12) y revisar errores en Console" -ForegroundColor White
}

Write-Host "`n   ?? Ver guía completa: " -NoNewline -ForegroundColor Gray
Write-Host "UNIDADMEDIDA-TROUBLESHOOTING.md" -ForegroundColor Cyan

Write-Host "`n??????????????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host ""
