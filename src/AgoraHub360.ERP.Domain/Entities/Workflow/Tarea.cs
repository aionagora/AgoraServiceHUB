namespace AgoraHub360.ERP.Domain.Entities.Workflow;

using System.Text.Json;
using AgoraHub360.ERP.Domain.Common;
using AgoraHub360.ERP.Domain.Entities.Core;

/// <summary>
/// Tarea polimórfica del workflow ERP.
/// Se asocia a cualquier documento padre mediante el par (EntityType, EntityId).
/// Valores válidos de EntityType: "OrdenPedido" | "OrdenCompra" | "OrdenVenta" | "Embarque".
/// </summary>
public class Tarea : TenantEntity
{
    public int Id { get; set; }

    // ?? Polimorfismo ??????????????????????????????????????????????????????????

    /// <summary>Tipo de documento padre. Ej: "OrdenPedido", "OrdenCompra", "OrdenVenta", "Embarque".</summary>
    public string EntityType { get; set; } = string.Empty;

    /// <summary>PK del documento padre (int genérico, join manual según EntityType).</summary>
    public int EntityId { get; set; }

    // ?? Definición de la tarea ????????????????????????????????????????????????

    /// <summary>Orden de ejecución dentro del documento padre (secuencia del workflow).</summary>
    public int Orden { get; set; }

    /// <summary>Código funcional corto. Ej: ETD, ETA, DUI, RECEP, PAGO.</summary>
    public string Codigo { get; set; } = string.Empty;

    /// <summary>Descripción legible de la tarea para mostrar en UI.</summary>
    public string Descripcion { get; set; } = string.Empty;

    // ?? Planificación ?????????????????????????????????????????????????????????

    /// <summary>Fecha planificada de ejecución (solo fecha, sin hora).</summary>
    public DateOnly? FechaPlan { get; set; }

    /// <summary>Fecha real en que se ejecutó o confirmó la tarea.</summary>
    public DateOnly? FechaReal { get; set; }

    // ?? Estado ????????????????????????????????????????????????????????????????

    /// <summary>Estado del ciclo de vida: PENDIENTE | EN_PROCESO | COMPLETADO | BLOQUEADO.</summary>
    public string Estado { get; set; } = "PENDIENTE";

    /// <summary>
    /// Flag de rendimiento que duplica Estado == "COMPLETADO".
    /// Permite filtros rápidos en índices sin evaluar nvarchar.
    /// </summary>
    public bool Completado { get; set; } = false;

    // ?? Responsable ???????????????????????????????????????????????????????????

    /// <summary>Nombre, email o área responsable de ejecutar la tarea.</summary>
    public string? Responsable { get; set; }

    /// <summary>Observaciones libres registradas al completar o bloquear la tarea.</summary>
    public string? Observaciones { get; set; }

    // ?? Metadata extendida ????????????????????????????????????????????????????

    /// <summary>
    /// JSON libre con metadata específica según tipo de tarea.
    /// Ej: { "Puerto": "Buenos Aires", "BL": "MSCUXXXXXXXX" } para tarea ETA.
    /// </summary>
    public string? MetadataJson { get; set; }

    // ?? Navegación ????????????????????????????????????????????????????????????

    public Empresa? Empresa { get; set; }

    // ?? Métodos ???????????????????????????????????????????????????????????????

    /// <summary>
    /// Deserializa MetadataJson al tipo <typeparamref name="T"/> indicado.
    /// Retorna null si MetadataJson es nulo.
    /// </summary>
    public T? GetMetadata<T>() where T : class
        => MetadataJson is null ? null : JsonSerializer.Deserialize<T>(MetadataJson);
}
