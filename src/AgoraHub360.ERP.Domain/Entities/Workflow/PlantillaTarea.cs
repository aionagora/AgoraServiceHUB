namespace AgoraHub360.ERP.Domain.Entities.Workflow;

using AgoraHub360.ERP.Domain.Common;
using AgoraHub360.ERP.Domain.Entities.Core;

/// <summary>
/// Plantilla de tarea del workflow ERP.
/// Define el catálogo de hitos estándar por tipo de documento y sub-tipo de operación.
/// EmpresaId = null  ? plantilla global del sistema (seed).
/// EmpresaId = X     ? plantilla personalizada de la empresa X.
/// </summary>
public class PlantillaTarea : AuditableEntity
{
    public int Id { get; set; }

    // ?? Clasificación ?????????????????????????????????????????????????????????

    /// <summary>
    /// Tipo de documento al que aplica la plantilla.
    /// Valores: "OrdenPedido" | "OrdenCompra" | "OrdenVenta" | "Embarque".
    /// </summary>
    public string EntityType { get; set; } = string.Empty;

    /// <summary>
    /// Sub-tipo de operación. Ej: "IMPORTACION", "TRASPASO_INTERNO".
    /// Null = aplica a todos los sub-tipos del EntityType.
    /// </summary>
    public string? SubTipo { get; set; }

    // ?? Definición del hito ???????????????????????????????????????????????????

    /// <summary>Posición en la secuencia del workflow (1-based).</summary>
    public int Orden { get; set; }

    /// <summary>Código funcional corto y único dentro del workflow. Ej: ETD, ETA, DUI, RECEP.</summary>
    public string Codigo { get; set; } = string.Empty;

    /// <summary>Descripción legible del hito para mostrar en UI y reportes.</summary>
    public string Descripcion { get; set; } = string.Empty;

    // ?? Comportamiento ????????????????????????????????????????????????????????

    /// <summary>
    /// Cuando true, el sistema completa automáticamente esta tarea
    /// (ej: creación del documento, cierre de expediente).
    /// </summary>
    public bool EsAutomatico { get; set; } = false;

    /// <summary>
    /// Rol del área responsable de ejecutar el hito.
    /// Ej: "ALMACEN", "COMPRAS", "LOGISTICA", "FINANZAS", "AGENTE_ADUANA", "SUPERVISOR", "GERENCIA".
    /// Null = cualquier usuario con acceso.
    /// </summary>
    public string? RolResponsable { get; set; }

    // ?? Tenant opcional ???????????????????????????????????????????????????????

    /// <summary>
    /// FK opcional a Empresa. Null = plantilla global; valor = plantilla privada de la empresa.
    /// </summary>
    public int? EmpresaId { get; set; }

    // ?? Navegación ????????????????????????????????????????????????????????????

    public Empresa? Empresa { get; set; }
}
