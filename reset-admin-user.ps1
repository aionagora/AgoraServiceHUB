# ???????????????????????????????????????????????????????????????
# SCRIPT: Reset Admin User
# Propósito: Resetea el usuario administrador del sistema
# Fecha: 2024-01-17
# ???????????????????????????????????????????????????????????????

Write-Host "`n????????????????????????????????????????????????????????????????" -ForegroundColor Red
Write-Host "?                                                              ?" -ForegroundColor Red
Write-Host "?    ?? RESETEO DE USUARIO ADMINISTRADOR                       ?" -ForegroundColor Red
Write-Host "?                                                              ?" -ForegroundColor Red
Write-Host "????????????????????????????????????????????????????????????????" -ForegroundColor Red

Write-Host "`n??  ADVERTENCIA:" -ForegroundColor Yellow
Write-Host "Este script ELIMINARÁ y RECREARÁ el usuario administrador." -ForegroundColor Yellow
Write-Host "Se perderán todos los datos asociados a este usuario.`n" -ForegroundColor Yellow

# Solicitar confirmación
$confirm = Read-Host "¿Desea continuar? (SI/NO)"
if ($confirm -ne "SI") {
    Write-Host "`n? Operación cancelada por el usuario." -ForegroundColor Red
    exit
}

Write-Host "`n??????????????????????????????????????????????????????????" -ForegroundColor DarkGray

# ???????????????????????????????????????????????????????????????
# PASO 1: Obtener cadena de conexión
# ???????????????????????????????????????????????????????????????
Write-Host "`n[1/4] ?? Leyendo configuración..." -ForegroundColor Cyan

$appSettingsPath = "src\AgoraHub360.ERP.Api\appsettings.json"

if (-not (Test-Path $appSettingsPath)) {
    Write-Host "? No se encontró el archivo appsettings.json" -ForegroundColor Red
    exit 1
}

try {
    $appSettings = Get-Content $appSettingsPath | ConvertFrom-Json
    $connectionString = $appSettings.ConnectionStrings.DefaultConnection
    
    Write-Host "   ? Configuración leída correctamente" -ForegroundColor Green
} catch {
    Write-Host "   ? Error al leer appsettings.json: $_" -ForegroundColor Red
    exit 1
}

# ???????????????????????????????????????????????????????????????
# PASO 2: Generar nuevo hash de contraseña
# ???????????????????????????????????????????????????????????????
Write-Host "`n[2/4] ?? Generando credenciales..." -ForegroundColor Cyan

# Nuevas credenciales
$email = "admin@agorahub360.com"
$username = "admin"
$password = "Admin123"
$fullName = "Administrador del Sistema"

# Generar hash SHA256 (mismo método que usa el sistema)
$sha256 = [System.Security.Cryptography.SHA256]::Create()
$bytes = [System.Text.Encoding]::UTF8.GetBytes($password)
$hashBytes = $sha256.ComputeHash($bytes)
$passwordHash = [Convert]::ToBase64String($hashBytes)

Write-Host "   Usuario: " -NoNewline -ForegroundColor Gray
Write-Host $username -ForegroundColor White
Write-Host "   Email: " -NoNewline -ForegroundColor Gray
Write-Host $email -ForegroundColor White
Write-Host "   Contraseña: " -NoNewline -ForegroundColor Gray
Write-Host $password -ForegroundColor White
Write-Host "   Hash: " -NoNewline -ForegroundColor Gray
Write-Host $passwordHash.Substring(0, 20) -NoNewline -ForegroundColor DarkGray
Write-Host "..." -ForegroundColor DarkGray

# ???????????????????????????????????????????????????????????????
# PASO 3: Ejecutar scripts SQL
# ???????????????????????????????????????????????????????????????
Write-Host "`n[3/4] ???  Conectando a la base de datos..." -ForegroundColor Cyan

try {
    # Importar módulo SqlServer si no está disponible
    if (-not (Get-Module -ListAvailable -Name SqlServer)) {
        Write-Host "   ??  Instalando módulo SqlServer..." -ForegroundColor Yellow
        Install-Module -Name SqlServer -Force -AllowClobber -Scope CurrentUser
    }
    
    Import-Module SqlServer -ErrorAction Stop
    
    Write-Host "   ? Conexión establecida" -ForegroundColor Green
    
    # Script SQL para resetear admin
    $sqlScript = @"
-- ???????????????????????????????????????????????????????????????
-- RESET USUARIO ADMINISTRADOR
-- ???????????????????????????????????????????????????????????????

BEGIN TRANSACTION;

BEGIN TRY
    PRINT '? Eliminando asignaciones de empresa...'
    DELETE FROM [core].[UsuarioEmpresas] WHERE UsuarioId = 1;
    
    PRINT '? Eliminando usuario existente...'
    DELETE FROM [core].[Usuarios] WHERE Id = 1;
    
    PRINT '? Verificando empresa demo...'
    IF NOT EXISTS (SELECT 1 FROM [core].[Empresas] WHERE Id = 1)
    BEGIN
        PRINT '? Creando empresa demo...'
        SET IDENTITY_INSERT [core].[Empresas] ON;
        INSERT INTO [core].[Empresas] 
            (Id, Nombre, NIT, Direccion, Telefono, Email, MonedaBaseId, FechaCreacion, Activo)
        VALUES 
            (1, 'AgoraHub360 - Empresa Demo', '1234567890', 'Av. Principal #123', '+591 12345678', 
             'demo@agorahub360.com', 'BOB', GETDATE(), 1);
        SET IDENTITY_INSERT [core].[Empresas] OFF;
    END
    
    PRINT '? Creando nuevo usuario administrador...'
    SET IDENTITY_INSERT [core].[Usuarios] ON;
    INSERT INTO [core].[Usuarios] 
        (Id, NombreUsuario, Email, PasswordHash, NombreCompleto, EmpresaActivaId, FechaCreacion, Activo)
    VALUES 
        (1, '$username', '$email', '$passwordHash', 
         '$fullName', 1, GETDATE(), 1);
    SET IDENTITY_INSERT [core].[Usuarios] OFF;
    
    PRINT '? Asignando rol Admin...'
    INSERT INTO [core].[UsuarioEmpresas] (UsuarioId, EmpresaId, Rol)
    VALUES (1, 1, 'Admin');
    
    COMMIT TRANSACTION;
    PRINT '? Usuario administrador reseteado exitosamente'
    
    -- Mostrar información del usuario
    PRINT ''
    PRINT '???????????????????????????????????????????????????????????????'
    PRINT 'INFORMACIÓN DEL USUARIO'
    PRINT '???????????????????????????????????????????????????????????????'
    SELECT 
        U.Id,
        U.NombreUsuario,
        U.Email,
        U.NombreCompleto,
        U.Activo,
        E.Nombre AS EmpresaActiva,
        UE.Rol
    FROM [core].[Usuarios] U
    LEFT JOIN [core].[Empresas] E ON U.EmpresaActivaId = E.Id
    LEFT JOIN [core].[UsuarioEmpresas] UE ON U.Id = UE.UsuarioId AND UE.EmpresaId = 1
    WHERE U.Id = 1;
    
END TRY
BEGIN CATCH
    ROLLBACK TRANSACTION;
    PRINT '? Error: ' + ERROR_MESSAGE();
    THROW;
END CATCH
"@
    
    Write-Host "`n   Ejecutando script SQL..." -ForegroundColor Gray
    
    # Ejecutar script
    Invoke-Sqlcmd -ConnectionString $connectionString -Query $sqlScript -Verbose
    
    Write-Host "`n   ? Script ejecutado exitosamente" -ForegroundColor Green
    
} catch {
    Write-Host "`n   ? Error al ejecutar script SQL:" -ForegroundColor Red
    Write-Host "   $_" -ForegroundColor Red
    exit 1
}

# ???????????????????????????????????????????????????????????????
# PASO 4: Verificación
# ???????????????????????????????????????????????????????????????
Write-Host "`n[4/4] ? Verificando resultado..." -ForegroundColor Cyan

try {
    $verificacion = @"
SELECT 
    U.Id,
    U.NombreUsuario,
    U.Email,
    U.Activo,
    E.Nombre AS EmpresaActiva,
    UE.Rol
FROM [core].[Usuarios] U
LEFT JOIN [core].[Empresas] E ON U.EmpresaActivaId = E.Id
LEFT JOIN [core].[UsuarioEmpresas] UE ON U.Id = UE.UsuarioId AND UE.EmpresaId = 1
WHERE U.Id = 1;
"@
    
    $resultado = Invoke-Sqlcmd -ConnectionString $connectionString -Query $verificacion
    
    if ($resultado) {
        Write-Host "`n   ? Usuario verificado correctamente" -ForegroundColor Green
        Write-Host "`n   Detalles del usuario:" -ForegroundColor Gray
        $resultado | Format-List
    } else {
        Write-Host "`n   ??  No se pudo verificar el usuario" -ForegroundColor Yellow
    }
    
} catch {
    Write-Host "`n   ??  No se pudo verificar (pero el reset pudo haberse completado)" -ForegroundColor Yellow
}

