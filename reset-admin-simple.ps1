    PRINT 'Usuario:    admin';
    PRINT 'Contraseña: $password';
    PRINT 'Rol:        Admin';
    PRINT '???????????????????????????????????????????????????????????????';
    
END TRY
BEGIN CATCH
    ROLLBACK TRANSACTION;
    
    PRINT '';
    PRINT '? ERROR AL RESETEAR USUARIO:';
    PRINT '   Mensaje: ' + ERROR_MESSAGE();
    PRINT '   Línea: ' + CAST(ERROR_LINE() AS VARCHAR);
    PRINT '   Procedimiento: ' + ISNULL(ERROR_PROCEDURE(), 'N/A');
    PRINT '';
    
    THROW;
END CATCH

GO
"@

