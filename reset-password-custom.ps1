Write-Host "????????????????????????????????????????????????????????????????" -ForegroundColor Cyan

# Nueva contraseña
$password = "Sinnada123.**"

# Generar hash SHA256
Write-Host "`n[1/3] ?? Generando hash de contraseña..." -ForegroundColor Yellow
$sha256 = [System.Security.Cryptography.SHA256]::Create()
$bytes = [System.Text.Encoding]::UTF8.GetBytes($password)
$hashBytes = $sha256.ComputeHash($bytes)
$passwordHash = [Convert]::ToBase64String($hashBytes)

Write-Host "   ? Hash generado exitosamente" -ForegroundColor Green
Write-Host "   Contraseña: " -NoNewline -ForegroundColor Gray
Write-Host $password -ForegroundColor Cyan
Write-Host "   Hash: " -NoNewline -ForegroundColor Gray
Write-Host $passwordHash -ForegroundColor DarkGray

# ???????????????????????????????????????????????????????????????
# Generar script SQL
# ???????????????????????????????????????????????????????????????
Write-Host "`n[2/3] ?? Generando script SQL..." -ForegroundColor Yellow

$sqlContent = @"
-- ???????????????????????????????????????????????????????????????
-- RESET CONTRASEÑA ADMINISTRADOR
-- Contraseña: $password
-- Hash: $passwordHash
-- Generado: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
-- ???????????????????????????????????????????????????????????????

USE [AgoraHub360ERP];
GO

BEGIN TRANSACTION;

BEGIN TRY
    PRINT '? Actualizando contraseña del administrador...';
    
    UPDATE [core].[Usuarios]
    SET PasswordHash = '$passwordHash'
    WHERE Id = 1;
    
    PRINT '   ? Contraseña actualizada';
    
    COMMIT TRANSACTION;
    PRINT '';
    PRINT '? Contraseña del administrador actualizada exitosamente';
    PRINT '';
    
    -- Verificación
    PRINT '???????????????????????????????????????????????????????????????';
    PRINT 'VERIFICACIÓN - DATOS DEL USUARIO';
    PRINT '???????????????????????????????????????????????????????????????';
    SELECT 
        U.Id,
        U.NombreUsuario,
        U.Email,
        U.Activo,
        E.Nombre AS EmpresaActiva
    FROM [core].[Usuarios] U
    LEFT JOIN [core].[Empresas] E ON U.EmpresaActivaId = E.Id
    WHERE U.Id = 1;
    
    PRINT '';
    PRINT '???????????????????????????????????????????????????????????????';
    PRINT 'NUEVAS CREDENCIALES DE ACCESO';
    PRINT '???????????????????????????????????????????????????????????????';
    PRINT 'Email:      admin@agorahub360.com';
    PRINT 'Usuario:    admin';
    PRINT 'Contraseña: $password';
    PRINT '???????????????????????????????????????????????????????????????';
    
END TRY
BEGIN CATCH
    ROLLBACK TRANSACTION;
    
    PRINT '';
    PRINT '? ERROR AL ACTUALIZAR CONTRASEÑA:';
    PRINT '   Mensaje: ' + ERROR_MESSAGE();
    PRINT '   Línea: ' + CAST(ERROR_LINE() AS VARCHAR);
    PRINT '';
    
    THROW;
END CATCH

GO
"@

$sqlFile = "reset-admin-password-custom.sql"
$sqlContent | Out-File -FilePath $sqlFile -Encoding UTF8

Write-Host "   ? Script SQL generado: " -NoNewline -ForegroundColor Green
Write-Host $sqlFile -ForegroundColor White

# ???????????????????????????????????????????????????????????????
# Ejecutar con SqlServer module si está disponible
# ???????????????????????????????????????????????????????????????
Write-Host "`n[3/3] ???  Intentando ejecutar automáticamente..." -ForegroundColor Yellow

try {
    # Leer connection string
    $appSettingsPath = "src\AgoraHub360.ERP.Api\appsettings.json"
    
    if (Test-Path $appSettingsPath) {
        $appSettings = Get-Content $appSettingsPath | ConvertFrom-Json
        $connectionString = $appSettings.ConnectionStrings.DefaultConnection
        
        # Intentar importar módulo SqlServer
        if (Get-Module -ListAvailable -Name SqlServer) {
            Import-Module SqlServer -ErrorAction Stop
            
            Write-Host "   ? Ejecutando script SQL..." -ForegroundColor Gray
            
            # Ejecutar script
            Invoke-Sqlcmd -ConnectionString $connectionString -Query $sqlContent
            
            Write-Host "   ? Contraseña actualizada exitosamente en la base de datos" -ForegroundColor Green
            
        } else {
            Write-Host "   ??  Módulo SqlServer no disponible" -ForegroundColor Yellow
            Write-Host "   ? Ejecuta manualmente el archivo SQL generado" -ForegroundColor Gray
        }
    } else {
        Write-Host "   ??  No se encontró appsettings.json" -ForegroundColor Yellow
        Write-Host "   ? Ejecuta manualmente el archivo SQL generado" -ForegroundColor Gray
    }
    
} catch {
    Write-Host "   ??  No se pudo ejecutar automáticamente: $_" -ForegroundColor Yellow
    Write-Host "   ? Ejecuta manualmente el archivo SQL generado" -ForegroundColor Gray
